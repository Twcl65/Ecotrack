"use client";

import { ChevronLeft, ChevronRight } from "lucide-react";
import { useMemo, useState } from "react";
import type { ReportFilters } from "@/types/reports";
import { exportReportExcel, exportReportPdf } from "@/lib/reports/export";
import type { GeneratedReport } from "@/types/reports";
import { REPORT_TYPE_META } from "@/types/reports";
import type { Complaint } from "@/types/complaint";
import type { Route } from "@/types/routes";
import type { Schedule } from "@/types/schedules";
import type { VehicleMaintenanceData } from "@/app/dashboard/report/vehicle-actions";

type Props = {
  reports: GeneratedReport[];
  filters: ReportFilters;
  schedules: Schedule[];
  complaints: Complaint[];
  routes: Route[];
  vehicleMaintenance: VehicleMaintenanceData[];
};

const PAGE_SIZE = 10;
const DISPLAYED_REPORT_TYPES = [
  "route",
  "collection",
  "complaint",
  "driver",
  "vehicle",
  "barangay",
] as const;

export default function RecentReportsTable({
  reports,
  filters,
  schedules,
  complaints,
  routes,
  vehicleMaintenance,
}: Props) {
  const [page, setPage] = useState(1);
  const [exportError, setExportError] = useState<string | null>(null);

  const exportData = { schedules, complaints, routes, vehicleMaintenance };

  function exportPdf(report: GeneratedReport) {
    setExportError(null);
    try {
      exportReportPdf(report, exportData);
    } catch (error) {
      setExportError(
        error instanceof Error ? error.message : "Could not open the PDF report."
      );
    }
  }

  function exportExcel(report: GeneratedReport) {
    setExportError(null);
    try {
      exportReportExcel(report, exportData);
    } catch (error) {
      setExportError(
        error instanceof Error ? error.message : "Could not download the Excel-compatible report."
      );
    }
  }

  const filtered = useMemo(() => {
    if (filters.fromDate > filters.toDate) return [];

    const list = reports
      .filter((report) => {
        if (!DISPLAYED_REPORT_TYPES.includes(
          report.reportType as (typeof DISPLAYED_REPORT_TYPES)[number]
        )) return false;
        if (filters.reportType !== "all" && report.reportType !== filters.reportType) {
          return false;
        }
        return (
          report.fromDate <= filters.toDate &&
          report.toDate >= filters.fromDate &&
          report.barangayFilter === (filters.barangay === "all" ? null : filters.barangay)
        );
      })
      .sort(
      (a, b) =>
        new Date(b.generatedAt).getTime() - new Date(a.generatedAt).getTime()
    );
    const latestByType = new Map<string, GeneratedReport>();
    for (const report of list) {
      if (!latestByType.has(report.reportType)) {
        latestByType.set(report.reportType, report);
      }
    }

    return DISPLAYED_REPORT_TYPES
      .map((type) => latestByType.get(type))
      .filter((report): report is GeneratedReport => Boolean(report));
  }, [reports, filters]);

  const totalPages = Math.max(1, Math.ceil(filtered.length / PAGE_SIZE));
  const currentPage = Math.min(page, totalPages);
  const pageItems = filtered.slice(
    (currentPage - 1) * PAGE_SIZE,
    currentPage * PAGE_SIZE
  );
  const rangeStart =
    filtered.length === 0 ? 0 : (currentPage - 1) * PAGE_SIZE + 1;
  const rangeEnd = Math.min(currentPage * PAGE_SIZE, filtered.length);

  return (
    <div className="dashboard-card flex min-h-0 flex-col overflow-hidden">
      <div className="border-b border-gray-100 px-4 py-3">
        <h3 className="text-sm font-bold text-gray-900">Recent Reports</h3>
      </div>

      {exportError && (
        <p role="alert" className="border-b border-red-100 bg-red-50 px-4 py-2 text-sm text-red-700">
          {exportError}
        </p>
      )}

      <div className="overflow-auto">
        <table className="w-full min-w-[720px] text-left text-sm">
          <thead className="border-b border-gray-200 bg-gray-50/95">
            <tr>
              {[
                "Report Name",
                "Type",
                "Period",
                "Generated By",
                "Date Generated",
                "Action",
              ].map((col) => (
                <th
                  key={col}
                  className="px-4 py-3 text-xs font-bold uppercase tracking-wide text-gray-700"
                >
                  {col}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {filtered.length === 0 ? (
              <tr>
                <td
                  colSpan={6}
                  className="px-4 py-8 text-center text-sm text-gray-500"
                >
                  No reports generated yet. Click &quot;Generate Reports&quot; to
                  create one.
                </td>
              </tr>
            ) : (
              pageItems.map((row) => {
                const meta =
                  REPORT_TYPE_META[
                    row.reportType as Exclude<typeof row.reportType, "all">
                  ];
                const Icon = meta.icon;
                return (
                  <tr
                    key={row.id}
                    className="border-b border-gray-100 last:border-0 hover:bg-gray-50/60"
                  >
                    <td className="px-4 py-3">
                      <div className="flex items-center gap-2">
                        <span
                          className={`flex h-8 w-8 shrink-0 items-center justify-center rounded-lg ${meta.iconBg}`}
                        >
                          <Icon className={`h-4 w-4 ${meta.iconColor}`} />
                        </span>
                        <span className="font-medium text-gray-900">
                          {row.reportName}
                        </span>
                      </div>
                    </td>
                    <td className="px-4 py-3 capitalize text-gray-700">
                      {row.reportType.replace("_", " ")}
                    </td>
                    <td className="px-4 py-3 text-gray-700">{row.periodLabel}</td>
                    <td className="px-4 py-3 text-gray-700">{row.generatedBy}</td>
                    <td className="px-4 py-3 text-gray-700">
                      <div>{row.dateLabel}</div>
                      <div className="text-xs text-gray-500">{row.timeLabel}</div>
                    </td>
                    <td className="px-4 py-3">
                      <div className="flex items-center gap-2">
                        <button
                          type="button"
                          onClick={() => exportPdf(row)}
                          className="rounded-md border border-eco-primary px-2.5 py-1 text-xs font-semibold text-eco-primary hover:bg-eco-light"
                        >
                          PDF
                        </button>
                        <button
                          type="button"
                          onClick={() => exportExcel(row)}
                          className="rounded-md border border-eco-primary px-2.5 py-1 text-xs font-semibold text-eco-primary hover:bg-eco-light"
                        >
                          Excel
                        </button>
                      </div>
                    </td>
                  </tr>
                );
              })
            )}
          </tbody>
        </table>
      </div>

      <div className="flex items-center justify-between border-t border-gray-100 px-4 py-2">
        <p className="text-xs text-gray-500">
          Showing {rangeStart} to {rangeEnd} of {filtered.length} entries
        </p>
        <div className="flex items-center gap-1">
          <button
            type="button"
            onClick={() => setPage((p) => Math.max(1, p - 1))}
            disabled={currentPage <= 1}
            className="rounded-md border border-gray-200 p-1.5 text-gray-600 disabled:opacity-40"
            aria-label="Previous page"
          >
            <ChevronLeft className="h-4 w-4" />
          </button>
          <span className="flex h-8 w-8 items-center justify-center rounded-md bg-eco-primary text-sm font-semibold text-white">
            {currentPage}
          </span>
          <button
            type="button"
            onClick={() => setPage((p) => Math.min(totalPages, p + 1))}
            disabled={currentPage >= totalPages}
            className="rounded-md border border-gray-200 p-1.5 text-gray-600 disabled:opacity-40"
            aria-label="Next page"
          >
            <ChevronRight className="h-4 w-4" />
          </button>
        </div>
      </div>
    </div>
  );
}
